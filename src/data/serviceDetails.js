export const serviceBySlug = Object.fromEntries(serviceDetails.map((service) => [service.slug, service]));
export const serviceByTitle = Object.fromEntries(serviceDetails.map((service) => [service.title.toLowerCase(), service]));

export function serviceSlug(title) {
  return title
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

export function servicePath(title) {
  const key = title.toLowerCase();
  const service = serviceByTitle[key];
  const alias = serviceAliases[key];
  return service ? `/services/${service.slug}` : alias ? `/services/${alias}` : '/contact';
}
